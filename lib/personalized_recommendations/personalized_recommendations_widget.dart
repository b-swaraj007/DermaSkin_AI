  List<RecommendationItem> get _morning =>
      _items.where((i) => i.isMorning).toList();
  List<RecommendationItem> get _evening =>
      _items.where((i) => i.isEvening).toList();
  List<RecommendationItem> get _weekly =>
      _items.where((i) => i.isWeekly).toList();

  List<RecommendationItem> _generateRecommendations(
    Map<String, SkinParameterResult>? r,
  ) {
    if (r == null) return const [];
    final items = <RecommendationItem>[];

    if ((r['pores']?.score ?? 100) < 70) {
      items.add(const RecommendationItem(
        ingredient: 'Niacinamide 10%',
        targets: 'Pore Congestion, Pigmentation',
        matchScore: 98,
        routine: 'Morning',
        benefits: ['Oil Control', 'Brightness'],
        reason: 'Your pore-congestion score suggests clogged pores. '
            'Niacinamide helps regulate sebum and refine pore appearance.',
      ));
    }
    if ((r['wrinkles']?.score ?? 100) < 75) {
      items.add(const RecommendationItem(
        ingredient: 'Retinol 0.3%',
        targets: 'Fine Lines, Texture',
        matchScore: 95,
        routine: 'Evening',
        benefits: ['Anti-Aging'],
        reason: 'Visible fine lines were detected. Retinol boosts cell '
            'turnover to smooth texture over time.',
      ));
    }
    if ((r['redness']?.score ?? 100) < 70) {
      items.add(const RecommendationItem(
        ingredient: 'Azelaic Acid 10%',
        targets: 'Redness, Acne Marks',
        matchScore: 92,
        routine: 'Evening',
        benefits: ['Soothing'],
        reason: 'Moderate redness detected. Azelaic acid calms '
            'inflammation and evens tone.',
      ));
    }
    if ((r['skin_type_moisture']?.score ?? 100) < 65) {
      items.add(const RecommendationItem(
        ingredient: 'Ceramide Complex',
        targets: 'Barrier Repair, Dryness',
        matchScore: 99,
        routine: 'Evening',
        benefits: ['Hydration'],
        reason: 'Low moisture levels suggest a compromised barrier. '
            'Ceramides restore lipid structure for lasting hydration.',
      ));
    }
    if ((r['uv_damage']?.score ?? 100) < 75) {
      items.add(const RecommendationItem(
        ingredient: 'Vitamin C 15%',
        targets: 'UV Damage, Brightening',
        matchScore: 91,
        routine: 'Morning',
        benefits: ['Antioxidant', 'Glow'],
        reason: 'UV markers detected. Vitamin C neutralises free '
            'radicals and fades sun-spots.',
      ));
    }
    if ((r['texture']?.score ?? 100) < 70) {
      items.add(const RecommendationItem(
        ingredient: 'AHA/BHA Exfoliant',
        targets: 'Dullness, Clogged Pores',
        matchScore: 90,
        routine: 'Weekly',
        benefits: ['Clarifying'],
        reason: 'Uneven texture detected. Gentle weekly exfoliation '
            'reveals smoother, clearer skin.',
      ));
    }

    // Hyaluronic acid always included — universally beneficial.
    items.add(const RecommendationItem(
      ingredient: 'Hyaluronic Acid 2%',
      targets: 'Moisture, Plumping',
      matchScore: 97,
      routine: 'Morning & Evening',
      benefits: ['Hydration', 'Plump'],
      reason: 'Hyaluronic acid draws water into the skin for an '
          'immediate plumping effect, suitable for all skin types.',
    ));

    return items;
  }

